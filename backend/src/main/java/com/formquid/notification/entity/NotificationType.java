package com.formquid.notification.entity;

public enum NotificationType {
    GENERAL,
    REGISTRATION_REQUEST,
    REGISTRATION_RECEIVED,
    REGISTRATION_APPROVED,
    REGISTRATION_REJECTED,
    ACCOUNT_UPDATED,
    ACCOUNT_SECURITY_CHANGED,
    COLLABORATION_INVITATION,
    COLLABORATION_REQUEST,
    COLLABORATION_ACCEPTED,
    COLLABORATION_REJECTED,
    COLLABORATION_REVOKED,
    COLLABORATION_PERMISSION_REDUCED,
    PUBLICATION_REQUEST,
    PUBLICATION_ACCEPTED,
    PUBLICATION_REJECTED,
    ELEMENT_REQUEST,
    ELEMENT_REQUEST_RESOLVED,
    SURVEY_STATUS_CHANGED,
    SURVEY_OWNERSHIP_TRANSFERRED;

    public boolean requiresEmail() {
        return switch (this) {
            case REGISTRATION_RECEIVED, REGISTRATION_APPROVED, REGISTRATION_REJECTED,
                ACCOUNT_SECURITY_CHANGED, COLLABORATION_REVOKED, COLLABORATION_PERMISSION_REDUCED -> true;
            default -> false;
        };
    }
}
