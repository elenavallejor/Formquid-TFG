-- Amplía las notificaciones para cubrir los cambios de cuenta, las colaboraciones y las encuestas.

ALTER TABLE notifications DROP CONSTRAINT ck_notifications_values;

ALTER TABLE notifications ADD CONSTRAINT ck_notifications_values CHECK (
    channel IN ('INTERNAL', 'EMAIL')
    AND type IN (
        'GENERAL', 'REGISTRATION_REQUEST', 'REGISTRATION_RECEIVED',
        'REGISTRATION_APPROVED', 'REGISTRATION_REJECTED', 'ACCOUNT_UPDATED',
        'ACCOUNT_SECURITY_CHANGED', 'COLLABORATION_INVITATION', 'COLLABORATION_REQUEST',
        'COLLABORATION_ACCEPTED', 'COLLABORATION_REJECTED', 'COLLABORATION_REVOKED',
        'COLLABORATION_PERMISSION_REDUCED', 'PUBLICATION_REQUEST', 'PUBLICATION_ACCEPTED',
        'PUBLICATION_REJECTED', 'ELEMENT_REQUEST', 'ELEMENT_REQUEST_RESOLVED',
        'SURVEY_STATUS_CHANGED', 'SURVEY_OWNERSHIP_TRANSFERRED'
    )
    AND target_type IN (
        'SURVEY', 'REGISTRATION_REQUEST', 'COLLABORATION_REQUEST',
        'PUBLICATION_REQUEST', 'ELEMENT_REQUEST', 'USER', 'QUESTION',
        'BLOCK', 'TEMPLATE', 'NONE'
    )
    AND recipient_user_id IS NOT NULL
);
